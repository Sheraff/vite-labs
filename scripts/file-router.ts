import { exec } from "node:child_process"
import { glob, mkdir, readFile, writeFile } from "node:fs/promises"
import { dirname, join, relative } from "node:path"
import { parseSync, Visitor, type ObjectExpression } from "oxc-parser"
import { createLogger, normalizePath, type Plugin } from "vite"

type Image = {
	key: string
	name: string
	importPath: string
	sourcePath: string
	absolutePath: string
}

type RouteMetaData = {
	title: string
	image?: string
	description?: string
	tags?: string[]
}

type RouteBuildMeta = {
	code: string
	data: RouteMetaData
	images: Image[]
}

type GitMeta = {
	lastModified: number
	firstAdded: number
}

type OutputBundle = Record<
	string,
	| {
			type: "asset"
			fileName: string
			originalFileNames?: string[]
	  }
	| {
			type: "chunk"
	  }
>

type Route = [key: string, meta: RouteBuildMeta, git: GitMeta]

const template = (routes: Array<Route>) => `// generated by file-router
/* eslint-disable */
import { type JSX, lazy } from "react"
${routes
	.map(([, { images }]) => images.map(({ name, importPath }) => `import ${name} from "${importPath}"`).join("\n"))
	.filter(Boolean)
	.join("\n")}

export type Routes = "${routes.map((r) => r[0]).join('" | "')}"

export type RouteMeta = {
	title: string
	image?: string
	description?: string
	tags?: string[]
}

export type GitMeta = {
	lastModified: number
	firstAdded: number
}

export type Route = {
	Component: React.LazyExoticComponent<() => JSX.Element>
	meta: RouteMeta
	git: GitMeta
}

export const ROUTES = {
${routes
	.map(
		([route, { code }, git]) => `	"${route}": {
		Component: lazy(() => import("./pages/${route}/index.tsx")),
		meta: ${code.split("\n").join("\n\t\t")},
		git: ${JSON.stringify(git, null, "\t").split("\n").join("\n\t\t")},
	}`,
	)
	.join(",\n")}
} as const satisfies Record<Routes, Route>
`

async function getGitMeta(index: string) {
	const dir = dirname(index)

	// Get last modification time for the entire directory
	const lastModTime = new Promise<number>((resolve, reject) => {
		exec(`git log -1 --pretty="format:%ai" -- "${dir}"`, (error, stdout, stderr) => {
			if (error || stderr) return reject(error || stderr)
			const timestamp = stdout.trim() ? new Date(stdout.trim()).getTime() : 0
			resolve(timestamp || 0)
		})
	})

	// Get first commit time for the entire directory
	const firstAddTime = new Promise<number>((resolve, reject) => {
		exec(
			`git log --diff-filter=A --format="%ad" --date=iso --reverse -- "${dir}" | head -1`,
			(error, stdout, stderr) => {
				if (error || stderr) return reject(error || stderr)
				const timestamp = stdout.trim() ? new Date(stdout.trim()).getTime() : 0
				resolve(timestamp || 0)
			},
		)
	})

	return {
		lastModified: await lastModTime,
		firstAdded: await firstAddTime,
	}
}

type Context = {
	resolve: (source: string, importer?: string | undefined) => Promise<{ id: string } | null>
	addWatchFile: (id: string) => void
}

const IMAGES = [".png", ".jpg", ".jpeg", ".gif", ".webp", ".svg", ".ico", ".bmp", ".tiff", ".avif"]

function fileNameToJSVariable(name: string) {
	return name.replace(/[^a-zA-Z0-9]/g, "_").replace(/^(\d)/, "_$1")
}

function getPropertyKey(prop: any) {
	if (prop.key.type === "Identifier") return String(prop.key.name)
	if (prop.key.type === "Literal" && typeof prop.key.value === "string") return prop.key.value
	return null
}

function toStaticValue(value: any): unknown {
	switch (value.type) {
		case "Literal":
			return value.value
		case "TemplateLiteral": {
			if (value.expressions.length > 0) throw new Error("Meta template literals cannot contain expressions")
			return value.quasis.map((quasi: any) => quasi.value?.cooked ?? quasi.value?.raw ?? "").join("")
		}
		case "ArrayExpression":
			return value.elements.map((element: any) => {
				if (!element || element.type === "SpreadElement") throw new Error("Meta arrays must be static")
				return toStaticValue(element)
			})
		default:
			throw new Error(`Unsupported meta value type: ${value.type}`)
	}
}

function sortDates(a: number, b: number) {
	if (a === b) return 0
	if (a === 0) return 1
	if (b === 0) return -1
	if (Number.isNaN(a)) return 1
	if (Number.isNaN(b)) return -1
	return a - b
}

function compareRoutes([aKey, , aGit]: Route, [bKey, , bGit]: Route) {
	const firstAdded = sortDates(bGit.firstAdded, aGit.firstAdded)
	if (firstAdded !== 0) return firstAdded

	const lastModified = sortDates(bGit.lastModified, aGit.lastModified)
	if (lastModified !== 0) return lastModified

	return aKey.localeCompare(bKey)
}

function withBase(base: string, path: string) {
	const normalizedBase = base.endsWith("/") ? base : `${base}/`
	const normalizedPath = path.startsWith("/") ? path.slice(1) : path
	return normalizedBase + normalizedPath
}

function getAssetLookup(bundle: OutputBundle) {
	const bySourcePath = new Map<string, string>()
	for (const fileName of Object.keys(bundle)) {
		const output = bundle[fileName]
		if (output.type !== "asset") continue
		for (const originalFileName of output.originalFileNames ?? []) {
			const normalized = normalizePath(originalFileName)
			bySourcePath.set(normalized, output.fileName)
			if (normalized.startsWith(normalizePath(process.cwd()) + "/")) {
				bySourcePath.set(normalizePath(relative(process.cwd(), normalized)), output.fileName)
			}
		}
	}
	return bySourcePath
}

function serializeProjects(routes: Route[], bundle: OutputBundle, base: string) {
	const assetLookup = getAssetLookup(bundle)
	return routes
		.filter(([, { data }]) => !data.tags?.includes("wip"))
		.toSorted(compareRoutes)
		.map(([route, { data, images }, git]) => {
			const imageImport = images.find((image) => image.key === "image")
			let image: string | null = null

			if (data.image) {
				const hashedPath =
					imageImport && (assetLookup.get(imageImport.sourcePath) ?? assetLookup.get(imageImport.absolutePath))
				if (!hashedPath) throw new Error(`Image asset not found for route \"${route}\"`)
				image = withBase(base, hashedPath)
			}

			return {
				route,
				url: withBase(base, route),
				title: data.title,
				description: data.description ?? null,
				tags: data.tags ?? [],
				image,
				git,
			}
		})
}

async function getMeta(key: string, index: string, ctx?: Context) {
	let code = `{ title: "${key}" }`
	let foundNode = false as ObjectExpression | false
	const data: RouteMetaData = { title: key }
	const images: Image[] = []
	const source = await readFile(index, "utf-8")
	try {
		const { program } = parseSync(index, source, {
			range: true,
		})
		const visitor = new Visitor({
			ExportNamedDeclaration(node) {
				if (foundNode) return
				if (node.declaration?.type !== "VariableDeclaration") return
				const decl = node.declaration.declarations[0]
				if (decl.type !== "VariableDeclarator") return
				if (decl.id.type !== "Identifier" || decl.id.name !== "meta") return
				if (decl.init?.type !== "ObjectExpression") throw new Error("Expected ObjectExpression")
				foundNode = decl.init
			},
		})
		visitor.visit(program)
	} catch (e) {
		console.error(e)
	}
	if (foundNode) {
		const start = foundNode.range![0]
		code = source.slice(start, foundNode.range![1])
		for (let i = foundNode.properties.length - 1; i >= 0; i--) {
			const prop = foundNode.properties[i]
			if (prop.type !== "Property") throw new Error("Expected Property in meta object for static analysis")

			const propKey = getPropertyKey(prop)
			if (!propKey) throw new Error("Expected static meta property key")

			const value = toStaticValue(prop.value)
			if (propKey === "title") {
				if (typeof value !== "string") throw new Error('Meta property "title" must be a string')
				data.title = value
			} else if (propKey === "description") {
				if (typeof value !== "string") throw new Error('Meta property "description" must be a string')
				data.description = value
			} else if (propKey === "image") {
				if (typeof value !== "string") throw new Error('Meta property "image" must be a string')
				data.image = value
			} else if (propKey === "tags") {
				if (!Array.isArray(value) || value.some((item) => typeof item !== "string")) {
					throw new Error('Meta property "tags" must be a string array')
				}
				data.tags = value as string[]
			}

			if (!ctx?.resolve || typeof value !== "string" || !IMAGES.some((image) => value.endsWith(image))) continue

			const resolved = await ctx.resolve(value, index)
			if (!resolved) continue

			const absolutePath = normalizePath(resolved.id)
			const importPath = "./" + normalizePath(relative(join(process.cwd(), "src"), resolved.id))
			const sourcePath = normalizePath(relative(process.cwd(), resolved.id))
			const name = fileNameToJSVariable(`${key}-${propKey}`)
			images.push({ key: propKey, name, importPath, sourcePath, absolutePath })
			code = code.slice(0, prop.value.range![0] - start) + name + code.slice(prop.value.range![1] - start)
		}
	}

	return { code, data, images }
}

export function fileRouter(): Plugin[] {
	const logger = createLogger("info", { prefix: "[file-router]" })
	let latestContent = ""
	let base = "/"
	const prefix = "src/pages/"
	const suffix = "/index.tsx"
	const pagesDir = join(process.cwd(), prefix)
	let routes: Array<Route> = []

	async function generate(ctx?: Context, event?: "add" | "change" | "unlink", file?: string) {
		const start = Date.now()
		let count = 0

		if (routes.length && event && file) {
			const key = file.slice(pagesDir.length, -suffix.length)
			const existingIndex = routes.findIndex(([k]) => k === key)
			count++
			if (event === "unlink") {
				if (existingIndex < 0) throw new Error(`route for removed file not found: ${key}`)
				routes.splice(existingIndex, 1)
			} else if (event === "add") {
				if (existingIndex >= 0) throw new Error(`route for added file already exists: ${key}`)
				const route = await Promise.all([key, getMeta(key, file, ctx), getGitMeta(file)])
				routes.push(route)
			} else if (event === "change") {
				if (existingIndex < 0) throw new Error(`route for changed file not found: ${key}`)
				const meta = await getMeta(key, file, ctx)
				routes[existingIndex][1] = meta
			}
		} else {
			const routePromises: Promise<Route>[] = []
			for await (const index of glob(`${prefix}**${suffix}`)) {
				count++
				const key = index.slice(prefix.length, -suffix.length)
				routePromises.push(Promise.all([key, getMeta(key, index, ctx), getGitMeta(index)]))
			}
			routes = await Promise.all(routePromises)
		}
		const content = template(routes)

		if (latestContent === content) return
		latestContent = content

		await writeFile("./src/router.ts", content)

		logger.info(`${event || "scan"} ${count} routes in ${Date.now() - start} ms`, { timestamp: true })
	}

	let dist = ""
	let ctx: Context | undefined = undefined

	return [
		{
			name: "file-router",
			enforce: "pre",
			configResolved(config) {
				base = config.base
			},
			configureServer(server) {
				const listener = (event: "add" | "change" | "unlink", file: string) =>
					file.startsWith(pagesDir) && file.endsWith("index.tsx") && generate(ctx, event, file)
				server.watcher.on("add", listener.bind(null, "add"))
				server.watcher.on("change", listener.bind(null, "change"))
				server.watcher.on("unlink", listener.bind(null, "unlink"))
			},
			async buildStart() {
				ctx = this
				await generate(this)
			},
		},
		{
			/*
			 * In "build" mode, we want to copy the index.html to the all the routes, so that
			 * a static file server can serve the routes.
			 */
			name: "file-router-post",
			enforce: "post",
			apply: "build",
			outputOptions(options) {
				dist = options.dir!
			},
			async writeBundle(_options, bundle) {
				const html = await readFile(join(dist, "index.html"), "utf-8")
				const projects = serializeProjects(routes, bundle, base)
				const projectsPath = join(dist, "projects.json")
				await writeFile(projectsPath, JSON.stringify(projects, null, 2) + "\n")
				this.info(projectsPath)
				this.info("copying index.html to routes")
				for (const [route] of routes) {
					const dir = join(dist, route)
					await mkdir(dir, { recursive: true })
					const target = join(dir, "index.html")
					await writeFile(target, html)
					this.info(target)
				}
			},
		},
	]
}
